#!/usr/bin/python3
"""Build a source archive from an explicit list; exclude all proprietary artifacts."""

import hashlib
import gzip
from pathlib import Path
import shutil
import tarfile

ROOT = Path(__file__).resolve().parents[1]
NAME = "deepcool-ak620g2-linux"
VERSION = "0.1.0"
files = ["README.md", "NOTICE.md", "LICENSE", "launcher.py", "service-launcher.py",
         "service-launcher-cli.py", "install-system.sh", "packaging/deepcool-linux",
         "packaging/deepcool-linux.desktop", "packaging/deepcool-linux.service",
         "packaging/arch/README.md", "tools/build-release.py"]
files.extend(str(p.relative_to(ROOT)) for p in sorted((ROOT / "docs").glob("*.md")))
files.extend(str(p.relative_to(ROOT)) for p in sorted((ROOT / "deepcool_linux").glob("*.py")))
files.extend(str(p.relative_to(ROOT)) for p in sorted((ROOT / "tests").glob("*.py")))
target = ROOT / "dist" / f"{NAME}-{VERSION}.tar.gz"
target.parent.mkdir(exist_ok=True)
with target.open("wb") as raw:
    with gzip.GzipFile(filename="", fileobj=raw, mode="wb", mtime=0) as compressed:
        with tarfile.open(fileobj=compressed, mode="w") as archive:
            for relative in files:
                info = archive.gettarinfo(ROOT / relative, arcname=f"{NAME}-{VERSION}/{relative}")
                info.uid = info.gid = info.mtime = 0
                info.uname = info.gname = ""
                info.mode = 0o644
                with (ROOT / relative).open("rb") as source:
                    archive.addfile(info, source)
digest = hashlib.sha256(target.read_bytes()).hexdigest()
arch = ROOT / "packaging/arch"
arch.mkdir(parents=True, exist_ok=True)
shutil.copyfile(target, arch / target.name)
template = '''# Generated by tools/build-release.py; packages this project's source only.
pkgname=deepcool-ak620g2-linux
pkgver=0.1.0
pkgrel=1
pkgdesc='Linux digital display controller for DeepCool AK620 G2 (3633:0029)'
arch=('any')
license=('GPL-3.0-or-later')
depends=('python')
optdepends=('tk: Chinese desktop control panel')
source=("$pkgname-$pkgver.tar.gz")
sha256sums=('@DIGEST@')

check() {
    cd "$srcdir/$pkgname-$pkgver"
    /usr/bin/python3 -m unittest discover -s tests
}

package() {
    cd "$srcdir/$pkgname-$pkgver"
    install -d "$pkgdir/usr/lib/deepcool-linux/deepcool_linux"
    install -m644 deepcool_linux/*.py "$pkgdir/usr/lib/deepcool-linux/deepcool_linux/"
    install -m644 launcher.py service-launcher.py service-launcher-cli.py \\
        "$pkgdir/usr/lib/deepcool-linux/"
    install -Dm755 packaging/deepcool-linux "$pkgdir/usr/bin/deepcool-linux"
    install -Dm644 packaging/deepcool-linux.desktop "$pkgdir/usr/share/applications/deepcool-linux.desktop"
    install -Dm644 packaging/deepcool-linux.service "$pkgdir/usr/lib/systemd/system/deepcool-linux.service"
    for document in README.md NOTICE.md LICENSE; do
        install -Dm644 "$document" "$pkgdir/usr/share/doc/$pkgname/$document"
    done
}
'''
(arch / "PKGBUILD").write_text(template.replace("@DIGEST@", digest))
print(target)
print("SHA-256:", digest)
